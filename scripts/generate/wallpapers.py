#!/usr/bin/env python3
"""Generate Embermine's built-in wallpaper path data from assets/wallpapers/*.svg.

Writes EmbermineWallpaperData.kt into a patched Firefox tree. Each wallpaper becomes a list of
filled shapes. A shape keeps its path data in viewBox units, with every transform and clip path
already applied, and a role index into the six-gray palette:

    role 0 #000000   role 1 #3E3B39   role 2 #6D6A6A
    role 3 #9B9A9C   role 4 #CAC9CD   role 5 #FFFFFF

A shape that lies inside its clip path keeps its curves. A shape that crosses its clip path is cut to
the clip and written as a polyline, because svgart samples curves at 12 steps per segment.

The generator fails on any other color, stroke, paint property or element, on a viewBox other than
542.16 x 920.73, and on a missing or unlisted SVG. Output is deterministic. Changing a wallpaper
needs only an SVG change, no patch edit.

    usage: wallpapers.py --tree <patched Firefox tree> [--assets <directory of the SVGs>]
"""

from __future__ import annotations

import argparse
import math
import re
import sys
import xml.etree.ElementTree as ET
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from svgart.geometry import format_number, path_data
from svgart.svgdoc import Document, Shape, parse_document

ASSETS_REL = "assets/wallpapers"
APP_SRC = "mobile/android/fenix/app/src"
FENIX_PACKAGE_DIR = f"{APP_SRC}/main/java/org/mozilla/fenix"
OUTPUT = f"{FENIX_PACKAGE_DIR}/embermine/wallpapers/EmbermineWallpaperData.kt"
WALLPAPERS = ("bloom", "grow", "pattern", "rise", "triangle")
VIEWBOX = (542.16, 920.73)
ROLE_GRAYS = ("#000000", "#3E3B39", "#6D6A6A", "#9B9A9C", "#CAC9CD", "#FFFFFF")
ROLE_BY_GRAY = {gray: role for role, gray in enumerate(ROLE_GRAYS)}
DIGITS = 2
# A Kotlin string constant must fit in one JVM class-file UTF8 entry, which holds 65535 bytes.
MAX_STRING_BYTES = 65535
_PATH_DATA = re.compile(r"[MLCZ0-9.,\-]+")
_ELEMENTS = frozenset({"svg", "g", "path", "rect", "defs", "clipPath", "title", "desc", "metadata"})
_SHAPE_ELEMENTS = frozenset({"path", "rect"})
_SHAPE_PROPERTIES = frozenset({"fill", "fill-rule"})
_PAINT_PROPERTIES = frozenset(
    {
        "fill",
        "fill-rule",
        "fill-opacity",
        "stroke",
        "stroke-width",
        "stroke-opacity",
        "opacity",
        "clip-rule",
        "filter",
        "mask",
        "display",
        "visibility",
    }
)
HEADER = [
    "/* This Source Code Form is subject to the terms of the Mozilla Public",
    " * License, v. 2.0. If a copy of the MPL was not distributed with this",
    " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */",
    "",
    "// Generated by scripts/generate/wallpapers.py from assets/wallpapers/*.svg. Do not edit.",
    "// A shape's role indexes the six-gray palette: " + ", ".join(f"{i} {g}" for i, g in enumerate(ROLE_GRAYS)) + ".",
    "// Paths are in viewBox units, with every transform and clip path already applied.",
    "",
    "package org.mozilla.fenix.embermine.wallpapers",
    "",
    "/** One filled shape of a wallpaper: [role] indexes the six-gray palette, [path] is SVG path data. */",
    "internal class EmbermineWallpaperShape(",
    "    val role: Int,",
    "    val evenOdd: Boolean,",
    "    val path: String,",
    ")",
    "",
    "/** One built-in wallpaper, with its shapes in paint order. */",
    "internal class EmbermineWallpaperArt(",
    "    val name: String,",
    "    val shapes: List<EmbermineWallpaperShape>,",
    ")",
    "",
]


class WallpaperError(ValueError):
    """An SVG, asset directory or source tree that the generator does not accept."""


@dataclass(frozen=True)
class Piece:
    """One filled shape of a wallpaper: palette role, fill rule and path data in viewBox units."""

    role: int
    even_odd: bool
    path: str


@dataclass(frozen=True)
class Artwork:
    """One wallpaper with its shapes in paint order."""

    name: str
    pieces: tuple[Piece, ...]


def convert(name: str, text: str) -> Artwork:
    """Read one wallpaper SVG. Raises WallpaperError for anything the generator does not support."""
    label = f"{name}.svg"
    try:
        root = ET.fromstring(text)
    except ET.ParseError as exc:
        raise WallpaperError(f"{label}: invalid SVG: {exc}") from exc
    _check_markup(label, root)
    try:
        document = parse_document(text)
    except ValueError as exc:
        raise WallpaperError(f"{label}: invalid SVG: {exc}") from exc
    if not (math.isclose(document.width, VIEWBOX[0]) and math.isclose(document.height, VIEWBOX[1])):
        raise WallpaperError(
            f"{label}: viewBox is 0 0 {document.width:g} {document.height:g}; "
            f"expected 0 0 {VIEWBOX[0]:g} {VIEWBOX[1]:g}"
        )
    return Artwork(name, _pieces(label, document))


def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def _declarations(el: ET.Element) -> dict[str, str]:
    """Paint declarations of one element: presentation attributes, then the style attribute."""
    declared = {key: value.strip() for key, value in el.attrib.items() if key in _PAINT_PROPERTIES}
    for item in (el.get("style") or "").split(";"):
        if ":" in item:
            key, _, value = item.partition(":")
            declared[key.strip()] = value.strip()
    return declared


def _check_markup(label: str, root: ET.Element) -> None:
    """Reject elements and paint declarations outside the subset the wallpapers use.

    Fill and fill-rule are read on paths and rects only, because SVG paint is inherited and the
    generator does not follow inheritance. Stroke is allowed only as none.
    """
    for el in root.iter():
        tag = _local(el.tag)
        if tag not in _ELEMENTS:
            raise WallpaperError(f"{label}: unsupported element <{tag}>")
        where = f"<{tag}" + (f' id="{el.get("id")}"' if el.get("id") else "") + ">"
        for name, value in _declarations(el).items():
            if name in _SHAPE_PROPERTIES and tag in _SHAPE_ELEMENTS:
                continue
            if name == "stroke" and value == "none":
                continue
            raise WallpaperError(
                f"{label}: {where} sets {name}: {value}; only fill and fill-rule on paths and rects, "
                "and stroke: none, are supported"
            )


def _role(label: str, shape: Shape) -> int:
    name = shape.name or "(no id)"
    if shape.fill is None:
        raise WallpaperError(f"{label}: shape {name} has fill none; use one of the six grays")
    role = ROLE_BY_GRAY.get(shape.fill)
    if role is None:
        raise WallpaperError(f"{label}: shape {name} uses colour {shape.fill}; allowed: {', '.join(ROLE_GRAYS)}")
    return role


def _pieces(label: str, document: Document) -> tuple[Piece, ...]:
    pieces: list[Piece] = []
    for shape in document.shapes:
        role = _role(label, shape)
        if not shape.subpaths:
            continue  # the clip path removed it completely
        pieces.append(Piece(role, shape.evenodd, path_data(shape.subpaths, DIGITS)))
    if not pieces:
        raise WallpaperError(f"{label}: no visible shapes")
    return tuple(pieces)


def load_all(assets: Path) -> list[Artwork]:
    """Convert the wallpapers in WALLPAPERS order. A missing or unlisted SVG is an error."""
    expected = {f"{name}.svg" for name in WALLPAPERS}
    present = {p.name for p in assets.glob("*.svg")}
    missing = sorted(expected - present)
    if missing:
        raise WallpaperError(f"{assets}: missing {', '.join(missing)}")
    unlisted = sorted(present - expected)
    if unlisted:
        raise WallpaperError(
            f"{assets}: {', '.join(unlisted)} is not listed in WALLPAPERS (scripts/generate/wallpapers.py)"
        )
    return [convert(name, (assets / f"{name}.svg").read_text(encoding="utf-8")) for name in WALLPAPERS]


def _kotlin_string(data: str) -> str:
    if not _PATH_DATA.fullmatch(data):
        raise WallpaperError(f"path data has characters outside M L C Z 0-9 . , -: {data[:40]!r}")
    size = len(data.encode("utf-8"))
    if size >= MAX_STRING_BYTES:
        raise WallpaperError(f"a path string is {size} bytes, over the {MAX_STRING_BYTES}-byte limit for one constant")
    return data


def render(artworks: Sequence[Artwork]) -> str:
    """The Kotlin source for the wallpapers. Pure function of its input, so output is deterministic."""
    lines = [
        *HEADER,
        "internal object EmbermineWallpaperData {",
        f"    const val VIEWBOX_WIDTH = {format_number(VIEWBOX[0], DIGITS)}f",
        f"    const val VIEWBOX_HEIGHT = {format_number(VIEWBOX[1], DIGITS)}f",
        "",
        "    val wallpapers: List<EmbermineWallpaperArt> = listOf(",
    ]
    for art in artworks:
        lines += [
            "        EmbermineWallpaperArt(",
            f'            name = "{art.name}",',
            "            shapes = listOf(",
        ]
        for piece in art.pieces:
            lines += [
                "                EmbermineWallpaperShape(",
                f"                    role = {piece.role},",
                f"                    evenOdd = {'true' if piece.even_odd else 'false'},",
                f'                    path = "{_kotlin_string(piece.path)}",',
                "                ),",
            ]
        lines += ["            ),", "        ),"]
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def _roles(art: Artwork) -> str:
    return ", ".join(str(role) for role in sorted({p.role for p in art.pieces}))


def run(tree: Path, assets: Path) -> Path:
    if not (tree / FENIX_PACKAGE_DIR).is_dir():
        raise WallpaperError(f"{tree} is not a Firefox source tree (no {FENIX_PACKAGE_DIR})")
    artworks = load_all(assets)
    text = render(artworks)
    out = tree / OUTPUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    for art in artworks:
        print(f"wallpaper {art.name}: {len(art.pieces)} paths (roles {_roles(art)})")
    total = sum(len(art.pieces) for art in artworks)
    print(f"wallpapers: wrote {OUTPUT} ({len(artworks)} wallpapers, {total} paths)")
    return out


def main(argv: list[str] | None = None) -> int:
    default_assets = Path(__file__).resolve().parents[2] / ASSETS_REL
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tree", required=True, type=Path, help="patched Firefox source tree")
    parser.add_argument("--assets", type=Path, default=default_assets, help="directory with the wallpaper SVGs")
    args = parser.parse_args(argv)
    try:
        run(args.tree.resolve(), args.assets.resolve())
    except WallpaperError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
